import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  Table,
  TableRow,
  TableCell,
  WidthType,
  AlignmentType,
  BorderStyle,
} from 'docx';
import { DocBlock, ResourceDocument } from './document-schema';

/**
 * DocxRenderer
 *
 * Builds a real Word (.docx) file from a ResourceDocument using the `docx`
 * library. Produces editable documents a teacher can open in Word/Google Docs:
 * headings, paragraphs, lists, tables, and numbered problem sets with a
 * separated answer key.
 */
export class DocxRenderer {
  static async toBuffer(doc: ResourceDocument): Promise<Buffer> {
    const children: (Paragraph | Table)[] = [];

    // Title block
    children.push(
      new Paragraph({
        children: [new TextRun({ text: doc.title, bold: true, size: 40 })], // 20pt
        spacing: { after: 80 },
      }),
    );
    if (doc.subtitle) {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: doc.subtitle, italics: true, size: 22, color: '444444' })],
          spacing: { after: 120 },
        }),
      );
    }
    const meta = doc.meta;
    if (meta) {
      const bits: string[] = [];
      if (meta.subject) bits.push(`Subject: ${meta.subject}`);
      if (meta.grade) bits.push(`Grade: ${meta.grade}`);
      if (meta.activityType) bits.push(meta.activityType);
      if (meta.studentName) bits.push(`For: ${meta.studentName}`);
      if (bits.length) {
        children.push(
          new Paragraph({
            children: [new TextRun({ text: bits.join('   •   '), size: 18, color: '666666' })],
            spacing: { after: 240 },
          }),
        );
      }
    }

    for (const block of doc.blocks) {
      children.push(...blockToDocx(block));
    }

    // Footnote
    children.push(
      new Paragraph({
        children: [new TextRun({ text: 'Generated by HackGB Curriculum Planning Assistant', size: 16, color: '999999' })],
        spacing: { before: 400 },
      }),
    );

    const document = new Document({
      styles: {
        default: {
          document: {
            run: { font: 'Calibri', size: 24 }, // 12pt
          },
        },
      },
      sections: [{ properties: {}, children }],
    });

    return Packer.toBuffer(document);
  }
}

function blockToDocx(b: DocBlock): (Paragraph | Table)[] {
  switch (b.kind) {
    case 'heading': {
      const level: (typeof HeadingLevel)[keyof typeof HeadingLevel] =
        b.level === 1 ? HeadingLevel.HEADING_1 : b.level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3;
      return [
        new Paragraph({
          heading: level,
          children: [new TextRun(b.text)],
          spacing: { before: 240, after: 120 },
        }),
      ];
    }
    case 'paragraph':
      return [
        new Paragraph({
          children: [new TextRun(b.text)],
          spacing: { after: 160 },
        }),
      ];
    case 'list':
      // Ordered lists are rendered with explicit numbers (simplest, always
      // correct); unordered lists use the built-in bullet.
      return b.items.map(
        (item, i) =>
          new Paragraph({
            children: [new TextRun(b.ordered ? `${i + 1}. ${item}` : item)],
            bullet: b.ordered ? undefined : { level: 0 },
            spacing: { after: 60 },
          }),
      );
    case 'table':
      return [
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          rows: [
            new TableRow({
              tableHeader: true,
              children: b.table.headers.map(
                (h) =>
                  new TableCell({
                    children: [new Paragraph({ children: [new TextRun({ text: h, bold: true })] })],
                    shading: { fill: 'F0F0F0' },
                    borders: cellBorders(),
                  }),
              ),
            }),
            ...b.table.rows.map(
              (row) =>
                new TableRow({
                  children: row.map(
                    (c) =>
                      new TableCell({
                        children: [new Paragraph({ children: [new TextRun(c)] })],
                        borders: cellBorders(),
                      }),
                  ),
                }),
            ),
          ],
        }),
        new Paragraph({ children: [new TextRun('')], spacing: { after: 120 } }),
      ];
    case 'problems':
      return [
        ...(b.label
          ? [
              new Paragraph({
                heading: HeadingLevel.HEADING_3,
                children: [new TextRun(b.label)],
                spacing: { before: 200, after: 100 },
              }),
            ]
          : []),
        ...b.problems.map(
          (p, i) =>
            new Paragraph({
              children: [
                new TextRun(`${i + 1}. ${p.text}`),
                ...(p.points ? [new TextRun({ text: `   [${p.points}]`, size: 18, color: '777777' })] : []),
              ],
              spacing: { after: 200 },
            }),
        ),
      ];
    case 'answerKey':
      return [
        new Paragraph({
          heading: HeadingLevel.HEADING_2,
          children: [new TextRun('Answer Key')],
          spacing: { before: 320, after: 120 },
        }),
        ...b.problems.map(
          (p, i) =>
            new Paragraph({
              children: [
                new TextRun(`${i + 1}. ${p.text}`),
                ...(p.answer ? [new TextRun({ text: ` — ${p.answer}`, bold: true })] : []),
                ...(p.solution ? [new TextRun({ text: `\nSolution: ${p.solution}`, size: 20, color: '444444' })] : []),
              ],
              spacing: { after: 100 },
            }),
        ),
      ];
    case 'callout':
      return [
        new Paragraph({
          children: [
            new TextRun({ text: `${(b.variant || 'note').toUpperCase()}: `, bold: true, size: 18, color: '555555' }),
            new TextRun(b.text),
          ],
          spacing: { before: 120, after: 160 },
        }),
      ];
    default:
      return [];
  }
}

function cellBorders() {
  const border = { style: BorderStyle.SINGLE, size: 4, color: '999999' };
  return { top: border, bottom: border, left: border, right: border };
}
